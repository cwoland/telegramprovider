import { describe, expect, it } from 'vitest';
import { chatIdToDigits, formatPhone, parseRecipient } from './phone';

describe('parseRecipient: валидные записи', () => {
    it.each([
        ['+7 999 123-45-67', '79991234567@c.us', '+7 (999) 123-45-67'],
        ['79991234567', '79991234567@c.us', '+7 (999) 123-45-67'],
        ['89991234567', '79991234567@c.us', '+7 (999) 123-45-67'],
        ['8 (999) 123-45-67', '79991234567@c.us', '+7 (999) 123-45-67'],
        ['9991234567', '79991234567@c.us', '+7 (999) 123-45-67'],
        ['  79991234567  ', '79991234567@c.us', '+7 (999) 123-45-67'],
        ['79991234567@c.us', '79991234567@c.us', '+7 (999) 123-45-67'],
        ['+380 44 123 4567', '380441234567@c.us', '+380441234567'],
    ])('«%s» → %s', (input, chatId, display) => {
        expect(parseRecipient(input)).toEqual({ ok: true, chatId, display });
    });
});

describe('parseRecipient: отказы', () => {
    it.each([
        ['', 'Введите номер телефона'],
        ['   ', 'Введите номер телефона'],
        ['не номер', 'Номер должен содержать цифры'],
        ['12345', 'Номер должен содержать от 10 до 15 цифр'],
        ['1234567890123456', 'Номер должен содержать от 10 до 15 цифр'],
        ['0123456789', 'Укажите номер с кодом страны, например +7 999 123-45-67'],
        ['123@c.us', 'Некорректный идентификатор чата'],
    ])('«%s» → ошибка «%s»', (input, error) => {
        expect(parseRecipient(input)).toEqual({ ok: false, error });
    });

    it('не подставляет код России, если пользователь указал «+»', () => {
        expect(parseRecipient('+8 999 123 45 67')).toEqual({
            ok: true,
            chatId: '89991234567@c.us',
            display: '+89991234567',
        });
    });
});

describe('formatPhone и chatIdToDigits', () => {
    it('форматирует только 11-значные номера с кодом 7', () => {
        expect(formatPhone('79991234567')).toBe('+7 (999) 123-45-67');
        expect(formatPhone('380441234567')).toBe('+380441234567');
    });

    it('снимает суффикс @c.us и не трогает строку без него', () => {
        expect(chatIdToDigits('79991234567@c.us')).toBe('79991234567');
        expect(chatIdToDigits('1777771364')).toBe('1777771364');
    });
});
